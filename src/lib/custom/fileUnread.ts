// ai-dvokat: что сказать юристу о вложении чата, из которого не извлечён текст (пакет 23.11, Д-6; правка по выкладке
// пакета 1). Сырая ошибка разбора (у Docling — английский текст с хэшем) юристу не показывается: она остаётся в
// консоли браузера и в журнале сервера. Сервис отдаёт ошибку только текстом, без кода, поэтому род причины (повреждён,
// пароль, не тот формат, сервис распознавания недоступен) различить нечем — одна общая фраза; по английскому тексту
// причина не угадывается.
import ru from '$lib/custom/locales/ru-RU.json';

/** Есть ли у вложения ошибка разбора (знак «не прочитан» показывается, пока она есть). */
export const isUnread = (error: unknown): boolean => !!error;

/** Подсказка у знака «не прочитан» — понятная причина словами для юриста, без сырой ошибки. */
export const unreadReason = (): string => ru.file_unread.reason;

